/**
 * `npm run typecheck:strict`: type-checks the whole program with `tsconfig.strict.json`
 * and fails when a path listed in `strictPaths.json` has a strict error (see `ratchet.ts`).
 */
import fs from "fs";
import path from "path";
import ts from "typescript";
import {
  evaluateRatchet,
  formatDiagnostic,
  type StrictDiagnostic,
} from "./ratchet";

const root = process.cwd();
const configPath = path.join(root, "tsconfig.strict.json");
const listPath = path.join(root, "scripts", "typecheck", "strictPaths.json");

const toRepoPath = (fileName: string): string =>
  path.relative(root, path.resolve(fileName)).split(path.sep).join("/");

const isProgramFile = (repoPath: string): boolean =>
  !repoPath.startsWith("..") &&
  !path.isAbsolute(repoPath) &&
  !repoPath.startsWith("node_modules/") &&
  !repoPath.startsWith(".next/") &&
  repoPath !== "next-env.d.ts"; // generated by Next, gitignored

function loadProgram(): ts.Program {
  const { config, error } = ts.readConfigFile(configPath, ts.sys.readFile);
  if (error) {
    console.error(ts.flattenDiagnosticMessageText(error.messageText, "\n"));
    process.exit(1);
  }
  const parsed = ts.parseJsonConfigFileContent(config, ts.sys, root, undefined, configPath);
  return ts.createProgram({
    rootNames: parsed.fileNames,
    options: parsed.options,
    projectReferences: parsed.projectReferences,
  });
}

function toStrictDiagnostic(d: ts.Diagnostic): StrictDiagnostic {
  const message = ts.flattenDiagnosticMessageText(d.messageText, "\n");
  if (!d.file || d.start === undefined) {
    return { file: d.file ? toRepoPath(d.file.fileName) : null, line: 1, column: 1, code: d.code, message };
  }
  const { line, character } = d.file.getLineAndCharacterOfPosition(d.start);
  return { file: toRepoPath(d.file.fileName), line: line + 1, column: character + 1, code: d.code, message };
}

const program = loadProgram();
const programFiles = program
  .getSourceFiles()
  .map((sf) => toRepoPath(sf.fileName))
  .filter(isProgramFile);
const programFileSet = new Set(programFiles);
const diagnostics = ts
  .getPreEmitDiagnostics(program)
  .map(toStrictDiagnostic)
  .filter((d) => d.file === null || programFileSet.has(d.file));
const strictPaths: string[] = JSON.parse(fs.readFileSync(listPath, "utf8"));

const { violations, unmatchedPaths, newlyClean } = evaluateRatchet({
  diagnostics,
  programFiles,
  strictPaths,
});

violations.forEach((d) => console.error(formatDiagnostic(d)));
unmatchedPaths.forEach((p) => console.error(`strict path matches no files: ${p}`));
if (newlyClean.length > 0) {
  console.log("Strict-clean but not listed (add to scripts/typecheck/strictPaths.json):");
  newlyClean.forEach((p) => console.log(`  ${p}`));
}

if (violations.length > 0 || unmatchedPaths.length > 0) {
  console.error(
    `Strict ratchet failed: ${violations.length} error(s) in strict paths, ${unmatchedPaths.length} unmatched path(s).`
  );
  process.exit(1);
}
console.log(`Strict ratchet: ${strictPaths.length} paths clean.`);
